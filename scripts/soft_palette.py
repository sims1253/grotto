def _apply_move(problem, role, lch, axis, d, hexes):
    """middle_palette._apply_move_fenced, then the chroma floor.

    The floor has to be applied to the MOVE, not only to the emitted hex: a
    move that lands below it is not a legal palette, and letting the search
    evaluate it anyway would make the floor invisible to the ascent.
    """
    got = mp._apply_move_fenced(problem, role, lch, axis, d, hexes)
    if got is None:
        return None
    return problem.fence_lch(role, *got)


def soft_refine(
    problem: SoftProblem,
    state: dict[str, tuple[float, float, float]],
    max_passes: int,
    moves=MOVES,
) -> tuple[dict[str, tuple[float, float, float]], dict]:
    """Coordinate ascent on UTILITY, one role at a time, fixed role order.

    Each candidate move is repaired into the feasible set (WCAG floors over the
    canvas and every co-occurring surface, gamut, and every taste fence) and
    scored with the same incremental pattern numeric_palette.greedy_refine
    uses: only the terms touching the moved role are recomputed, the shortfall
    is re-summed from the cached term values, and the emphasis term is
    re-summed from the ~40 roles the area table covers.

    Acceptance is STRICT on utility.  There is deliberately no mean-margin
    tie-break: an uncapped tie-break is exactly the incentive the proposal
    asks to remove, and it would let the search buy margin the shortfall
    already scores at zero.

    Acceptance is LEXICOGRAPHIC per role: first fewer salience/prominence
    reversals the moved role takes part in, then utility.  The objective
    cannot see salience, so without this the ascent walks into palettes the
    post-repair cannot recover: once the surfaces had a lightness axis it
    parked ``error`` at L 0.92, C 0.02 -- near-white, below ``breakpoint`` in
    normalised chroma by 0.19, a gap no bounded repair closes.  A reversal
    the gate would reject is never worth any utility, so ranking it first
    costs nothing admissible, and it lets the ascent climb OUT of a reversal
    a random start put it in.
    """
    from grotto.color import hex_to_oklch

    hexes = problem.hexes(state)
    terms = problem.terms
    vals = problem.term_values(hexes)
    exp = sm.SHORTFALL_EXP
    loss_total = sum(max(0.0, 1.0 - v) ** exp for v in vals)
    loss = loss_total / max(len(vals), 1)
    chroma = problem.chroma_table(hexes)
    emph = problem.emphasis_from(chroma)
    util = problem.utility_from(hexes, loss)

    def eval_with(role: str, new_hex: str):
        """(utility, delta) with only this role's terms recomputed.

        The shortfall is a SUM over the whole term table, but a move on one
        role can only change that role's terms -- so the sum is maintained
        incrementally (adjust the delta, add it to a running total) instead
        of re-reduced over all 187 terms per candidate.  Same numbers, O(terms
        for this role) instead of O(all terms).
        """
        ids = problem.term_ids_by_role.get(role, ())
        updates = {}
        delta = 0.0
        for i in ids:
            t = terms[i]
            pair = {
                t["a"]: new_hex if t["a"] == role else hexes[t["a"]],
                t["b"]: new_hex if t["b"] == role else hexes[t["b"]],
            }
            v2 = sm.term_value(t, pair)
            v1 = vals[i]
            updates[i] = v2
            delta += max(0.0, 1.0 - v2) ** exp - max(0.0, 1.0 - v1) ** exp
        e = emph
        w = problem._emph_roles.get(role, 0.0)
        if w > 0.0:
            e += w * (hex_to_oklch(new_hex)[1] - chroma.get(role, 0.0)) / problem._emph_total
        excess = max(0.0, (e - sm.EMPHASIS_BUDGET) / sm.EMPHASIS_BUDGET)
        sep2 = (loss_total + delta) / max(len(vals), 1)
        return 1.0 - sep2 - sm.EMPHASIS_WEIGHT * excess, updates

    for _ in range(max_passes):
        improved = False
        for role in problem.chromatic:
            if not problem.term_ids_by_role.get(role) and role not in problem._emph_roles:
                continue
            best = None
            best_util = util
            best_rev = _reversals_at(problem, hexes, role, hexes[role])
            for axis, d in moves:
                got = _apply_move(problem, role, state[role], axis, d, hexes)
                if got is None:
                    continue
                new_hex = oklch_to_hex(np_.project_chroma(*problem.fence_lch(role, *got)))
                u, updates = eval_with(role, new_hex)
                rev = _reversals_at(problem, hexes, role, new_hex)
                if rev < best_rev or (rev == best_rev and u > best_util + 1e-12):
                    best_rev = rev
                    best_util = u
                    best = (got, new_hex, updates)
            if best is not None:
                got, new_hex, updates = best
                state[role] = got
                hexes[role] = new_hex
                for i, v2 in updates.items():
                    delta = max(0.0, 1.0 - v2) ** exp - max(0.0, 1.0 - vals[i]) ** exp
                    loss_total += delta
                    vals[i] = v2
                if role in chroma:
                    chroma[role] = hex_to_oklch(new_hex)[1]
                loss = loss_total / max(len(vals), 1)
                emph = problem.emphasis_from(chroma)
                util = best_util
                improved = True
        if not improved:
            break

    return state, problem.state_score(state)


def run_search(
    problem: SoftProblem,
    seed: int = DEFAULT_SEED,
    restarts: int = 8,
    samples: int = 8,
    refine_passes: int = 12,
    refine_top: int = 2,
    moves=MOVES,
    log=None,
) -> list[dict]:
    """Multi-start sampling, then coordinate ascent on UTILITY.

    Each result: {'state', 'utility', 'sep', 'emph', 'kind'}.  Deterministic
    for a fixed (problem, seed, restarts, samples, moves).
    """
    rng = random.Random(seed)
    kinds = ("ladder", "bladder", "bseed", "free")
    results: list[dict] = []
    for ri in range(restarts):
        kind = kinds[ri % len(kinds)]
        pool = []
        for _ in range(samples):
            st = mp._initial_state_fenced(problem, rng, kind)
            # The sampler only knows the middle windows; bring the sample's
            # AUTHORED coordinates into the soft ones, as every later move is.
            st = {r: problem.fence_lch(r, *v) for r, v in st.items()}
            pool.append((problem.state_score(st)["utility"], st))
        pool.sort(key=lambda t: -t[0])
        for _, st in pool[:refine_top]:
            st2, sc = soft_refine(problem, st, refine_passes, moves=moves)
            results.append({"state": st2, "kind": kind, **sc})
        if log:
            best = max(results, key=lambda r: r["utility"])
            log(
                f"[restart {ri + 1}/{restarts} kind={kind}] best utility "
                f"{best['utility']:.4f} (sep {best['sep']:.4f}, emph {best['emph']:.4f})"
            )
    results.sort(key=lambda r: (-r["utility"], r["sep"], r["emph"]))
    seen: set = set()
    unique = []
    for r in results:
        key = tuple(
            sorted((k, round(v[0], 4), round(v[1], 4), round(v[2], 3)) for k, v in r["state"].items())
        )
        if key in seen:
            continue
        seen.add(key)
        unique.append(r)
    return unique


#: Rounding the YAML writer applies to authored coordinates before they are
#: turned back into a hex.  Reproduced exactly so the search can predict, not
#: guess, what the written file will contain.
_YAML_L = 6
_YAML_H = 4


def shipped_hexes(problem: SoftProblem, state: dict) -> dict[str, str]:
    """The hexes the WRITTEN palette will contain, computed without writing.

    ``write_palette_yaml`` stores authored OKLCH rounded to 6/4 decimals and
    ``Palette.from_yaml`` converts that back to a hex.  The result can differ
    by one 8-bit step from ``problem.hexes(state)`` -- enough to turn a
    salience pair the repair believes it fixed into one the gate reads as
    still broken.  Since the hex IS the theme, every constraint and repair in
    this script is evaluated against the hexes the file will really carry.

    The authored coordinates deliberately stay strictly inside the fences
    (``fence_audit_state`` allows no quantisation slack), so this is not a
    licence for the hexes to leave them: ``fence_audit`` keeps the 0.006
    lightness tolerance for exactly that one-step rounding.
    """
    out = dict(problem.scaffold_hex)
    for r, (L, C, h) in state.items():
        rounded = (round(L, _YAML_L), round(C, _YAML_L), round(h % 360.0, _YAML_H))
        out[r] = oklch_to_hex(np_.project_chroma(*rounded))
    return out


def repair_wcag(problem: SoftProblem, state: dict, rounds: int = 8) -> list[str]:
    """Restore every WCAG floor on the SHIPPED hexes after a repair pass.

    Why this exists: a repair that nudges a surface by one lightness step can
    push its 8-bit hex across a contrast floor the authored coordinates still
    satisfied (``wcag line_number on diff_changed: 2.999 < 3.0``).  The floor
    is a property of the hex the user sees, so it is re-established on the
    hex, not on the coordinates.

    Moves the SURFACE, never the ink: the inks carry the reading baseline, and
    the surfaces are what a repair pass was adjusting.  Scaffold surfaces
    cannot move and are left for the caller to report.
    """
    import re

    for _ in range(rounds):
        hexes = shipped_hexes(problem, state)
        bad = np_.check_feasible(problem, hexes)
        if not bad:
            return []
        progressed = False
        for entry in bad:
            m = re.match(r"(?:inherited: )?wcag (\S+) on (\S+): ", entry)
            if not m:
                continue
            surf = m.group(2)
            if surf not in problem.chromatic:
                continue  # scaffold surface: not ours to move
            # The wash moves toward the canvas and away from the inks: down
            # at night, up by day.
            d = 0.004 if problem.polarity == "light" else -0.004
            got = _apply_move(problem, surf, state[surf], "L", d, hexes)
            if got is None or (got[0] - state[surf][0]) * d <= 1e-9:
                continue
            state[surf] = got
            hexes = shipped_hexes(problem, state)
            progressed = True
        if not progressed:
            break
    return np_.check_feasible(problem, shipped_hexes(problem, state))


