class SoftProblem(mp.MiddleProblem):
    """MiddleProblem plus the soft-objective bookkeeping.

    The fences, floors, pair list and term table are inherited exactly; this
    subclass only adds the emphasis area table (constant across a run) and a
    cached per-role chroma accessor, because the emphasis sum is the one part
    of the objective that touches every role rather than the few the term
    table constrains.
    """

    def __init__(self, chromatic=tuple(np_.CHROMATIC_ROLES), profile: str = "default"):
        prof = PROFILES[profile]
        super().__init__(chromatic=chromatic,
                         scaffold_source=prof.get("scaffold_source", np_.SCAFFOLD_SOURCE))
        self.profile = profile
        self.prof = prof
        # Scaffold lightness overrides (see SCAFFOLD_L_OVERRIDES).  Applied
        # before anything reads a scaffold hex, so the WCAG caps they induce
        # on the highlight surfaces are the overridden ones.  The Night
        # overrides are Night numbers; Day solves its own.
        overrides = dict(SCAFFOLD_L_OVERRIDES) if self.polarity == "dark" else {}
        if prof.get("match_night_contrast"):
            from grotto.contrast import wcag_contrast

            night = np_._load_scaffold_source()
            night_bg = oklch_to_hex(np_.project_chroma(*night["bg"]))
            for r in NIGHT_MATCHED_INKS:
                L, C, h = night[r]
                L = SCAFFOLD_L_OVERRIDES.get(r, L)
                ratio = wcag_contrast(oklch_to_hex(np_.project_chroma(L, C, h)), night_bg)
                _, C, h = self.scaffold[r]
                overrides[r] = _solve_l_for_ratio(ratio, C, h, self.scaffold_hex["bg"])
            # The chromatic inks' fence CENTRES move the same way: candidate-b
            # day's syntax sits at ~5.5:1 at best, so on any tinted highlight
            # its inks had no legal lightness at all.  Each ink is centred
            # where it reaches the contrast candidate-b NIGHT gives it, with
            # Day's own hue and chroma.
            for r in self.chromatic:
                if self.paint[r] not in ("ink", "border"):
                    continue
                L, C, h = night[r]
                ratio = wcag_contrast(oklch_to_hex(np_.project_chroma(L, C, h)), night_bg)
                ratio = min(ratio, prof.get("ink_ratio_cap", ratio))
                _, Cd, hd = self.baseline_lch[r]
                self.baseline_lch[r] = (
                    _solve_l_for_ratio(ratio, Cd, hd, self.scaffold_hex["bg"]), Cd, hd)
        for r, L in {**overrides, **self.prof["scaffold_l"]}.items():
            _, C, h = self.scaffold[r]
            self.scaffold[r] = (L, C, h)
            self.scaffold_hex[r] = oklch_to_hex(np_.project_chroma(L, C, h))
        self.area = sm.area_table()
        # Instrument v2's surface terms: the search optimises exactly the term
        # table the instrument scores (soft_metric.surface_terms).
        self.terms = sm.instrument_terms(self, channel_credit=self.prof["channel_credit"])
        self.term_ids_by_role = {}
        for i, t in enumerate(self.terms):
            for r in (t["a"], t["b"]):
                self.term_ids_by_role.setdefault(r, []).append(i)
        # Roles the emphasis sum counts, with their weights resolved once.
        self._emph_roles = {
            r: float(self.area[r]["weight"])
            for r in self.area
            if r in self.present and float(self.area[r]["weight"]) > 0.0
        }
        self._emph_total = sum(self._emph_roles.values()) or 1.0
        # Salience pairs the gate checks (adjacent, non-tied members of a hue
        # family), indexed by role for the ascent's reversal guard.
        roles = self.roles_spec.roles
        fams: dict[str, list[str]] = {}
        for r in self.chromatic:
            fams.setdefault(roles[r].family, []).append(r)
        self.sal_pairs: dict[str, list[tuple[str, str]]] = {}
        for members in fams.values():
            sr = sorted(members, key=lambda r: roles[r].salience)
            for lo, hi in zip(sr, sr[1:]):
                if roles[lo].salience != roles[hi].salience:
                    self.sal_pairs.setdefault(lo, []).append((lo, hi))
                    self.sal_pairs.setdefault(hi, []).append((lo, hi))
        # Surface prominence pairs: every (lower, higher)-salience pair of
        # highlight SURFACES inside one hue family (see prominence_violations).
        self.prom_pairs: dict[str, list[tuple[str, str]]] = {}
        for members in fams.values():
            surf = [r for r in members if self.paint[r] == "surface"]
            for lo in surf:
                for hi in surf:
                    if roles[lo].salience < roles[hi].salience:
                        self.prom_pairs.setdefault(lo, []).append((lo, hi))
                        self.prom_pairs.setdefault(hi, []).append((lo, hi))

    def term_values(self, hexes: dict[str, str]) -> list[float]:
        return [sm.term_value(t, hexes) for t in self.terms]

    # -- lightness fences ------------------------------------------------

    def l_range(self, role: str) -> tuple[float, float]:
        """The middle fence, widened for roles that DECLARE lightness.

        ``spec/roles.yaml`` lists ``lightness_offset`` among the redundant
        channels of selection, search_match_current, the diff washes, error,
        success and focus -- and ``spec/distance-matrix.yaml`` names
        "lightness_and_icon" / "lightness_and_gutter_sign" as the redundant
        encoding of error/warning and diff_added/diff_removed.  A fence of
        +/-0.06 cannot deliver that channel: the redundant-channel audit
        (docs/review/redundant-channel-audit.md §8) measured that the worst
        surface has to move 0.0985 (normal) to 0.1734 (deutan).  So the spec's
        own declaration widens the fence, role by role; every other role keeps
        the middle frontier's fence unchanged.
        """
        lo, hi = super().l_range(role)
        if role in ROLE_L_MAX:
            hi = min(hi, ROLE_L_MAX[role])
        if role in self.prof.get("role_l", {}):
            return self.prof["role_l"][role]
        light = self.polarity == "light"
        if "lightness_offset" in self.roles_spec.roles[role].redundant_channels:
            base = self.baseline_lch[role][0]
            if self.paint[role] in ("ink", "border"):
                # Inks widen TOWARD the canvas only (down at night, up by
                # day): at night candidate-b's inks already sit at L
                # 0.80-0.89, and above that the sRGB gamut holds too little
                # chroma for the hue to survive (an early probe parked
                # ``error`` at L 0.96, C 0.012 -- white, below the floor).
                if light:
                    hi = max(hi, base + OFFSET_INK_L_DELTA)
                else:
                    lo = min(lo, base - OFFSET_INK_L_DELTA)
            else:
                lo = min(lo, base - OFFSET_SURFACE_L_DELTA)
                hi = max(hi, base + OFFSET_SURFACE_L_DELTA)
        if self.paint[role] == "surface":
            lo, hi = lo - self.prof["surf_l_extra"], hi + self.prof["surf_l_extra"]
            # A highlight is a wash on the far side of the canvas from the
            # inks: the middle repair already holds surfaces 0.01 off the
            # canvas, but the fence did not, and a wider fence let
            # ``selection`` sink to L 0.085 -- a near-black hole under a
            # 0.165 canvas, too dark to carry its hue.
            if light:
                hi = min(hi, self.scaffold["bg"][0] - 0.01)
            else:
                lo = max(lo, self.scaffold["bg"][0] + 0.01)
        if self.prof["ink_l_down"] and self.paint[role] in ("ink", "border"):
            if light:
                hi = max(hi, min(hi + self.prof["ink_l_down"], self.prof["ink_l_max"]))
            else:
                lo = min(lo, max(lo - self.prof["ink_l_down"], self.prof["ink_l_min"]))
        return (lo, hi)

    def chroma_floor(self, role: str) -> float:
        """Declared floor for a chromatic role (soft_metric.CHROMA_FLOOR).

        Every inherited fence is a ceiling.  A ceiling-only feasible set has a
        degenerate optimum, and this objective walks straight into it: a term
        that has cleared its threshold contributes exactly zero, so grey is
        always the cheapest way to stay cleared.  Run 0 of this session
        rendered ``error`` at C 0.0011 for exactly that reason -- the same
        pathology NUMERIC.md sections 5.3 and 10 record for the numeric and
        middle frontiers.  The floor is the repo's own HUE_AUDIT_MIN_CHROMA,
        reused rather than reinvented.
        """
        floor = max(sm.CHROMA_FLOOR, ROLE_CHROMA_FLOOR.get(role, 0.0))
        if role in np_.CATEGORICAL_ROLES:
            floor = max(floor, SYNTAX_CHROMA_FLOOR)
        return floor

    def fence_lch(self, role, L, C, h):
        """MiddleProblem.fence_lch, inside the soft hue windows, plus the
        chroma floor: raise chroma to it."""
        L, C, h = super().fence_lch(role, L, C, soft_project_hue(role, h))
        floor = self.chroma_floor(role)
        if C < floor:
            # A floor the gamut cannot hold at this lightness (a blue near
            # L 0.9 at night, a dark yellow near L 0.3 by day) is met by
            # moving to the NEAREST lightness inside the fence that can hold
            # it, not by clipping chroma below it.
            if self.chroma_ceiling(role, L, h) < floor:
                lo, hi = self.l_range(role)
                for k in range(1, 200):
                    for L2 in (L - 0.005 * k, L + 0.005 * k):
                        if lo <= L2 <= hi and self.chroma_ceiling(role, L2, h) >= floor:
                            L = L2
                            break
                    else:
                        continue
                    break
            C = min(floor, self.chroma_ceiling(role, L, h))
            # If the ceiling is below the floor the role cannot be legal; keep
            # the ceiling so the WCAG/gamut repairs still govern and the fence
            # audit reports it rather than silently emitting grey.
            C = max(C, 0.0)
        return (L, C, h)

    def chroma_ceiling(self, role: str, L: float, h: float) -> float:
        c = super().chroma_ceiling(role, L, h)
        cap = self.prof.get("surface_cap")
        if cap is not None and role in mp.HIGHLIGHT_SURFACE_ROLES:
            c = min(c, max(0.0, cap - mp.CHROMA_MARGIN))
        return c

    def fence_audit(self, hexes):
        """The middle audit plus the narrower soft hue windows."""
        out = super().fence_audit(hexes)
        cap = self.prof.get("surface_cap")
        if cap is not None:
            for r in mp.HIGHLIGHT_SURFACE_ROLES:
                if r in hexes and hex_to_oklch(hexes[r])[1] > cap + mp.CHROMA_AUDIT_TOL:
                    out.append(f"chroma {r}: {hex_to_oklch(hexes[r])[1]:.4f} > profile surface cap {cap}")
        for r in SOFT_HUE_WINDOWS:
            L, C, h = hex_to_oklch(hexes[r])
            if C >= mp.HUE_AUDIT_MIN_CHROMA and not _in_soft_window(r, h, mp.HUE_AUDIT_TOL):
                out.append(f"hue {r}: {h:.2f} outside soft window {SOFT_HUE_WINDOWS[r]}")
        return out

    def fence_audit_state(self, state):
        out = super().fence_audit_state(state)
        for r in SOFT_HUE_WINDOWS:
            if r in state and not _in_soft_window(r, state[r][2]):
                out.append(f"hue {r}: {state[r][2]:.2f} outside soft window {SOFT_HUE_WINDOWS[r]}")
        return out

    # -- emphasis ---------------------------------------------------------

    def chroma_table(self, hexes: dict[str, str]) -> dict[str, float]:
        """Chroma of every weighted role, keyed by role (for incremental use)."""
        from grotto.color import hex_to_oklch

        return {
            r: (hex_to_oklch(hexes[r])[1] if r in hexes else 0.0)
            for r in self._emph_roles
        }

    def emphasis_from(self, chroma: dict[str, float]) -> float:
        """Area-weighted mean chroma over the whole palette (canvas excluded)."""
        acc = 0.0
        for r, w in self._emph_roles.items():
            acc += w * chroma.get(r, 0.0)
        return acc / self._emph_total

    def emphasis(self, hexes: dict[str, str]) -> float:
        return self.emphasis_from(self.chroma_table(hexes))

    # -- objective --------------------------------------------------------

    def utility_from(self, hexes: dict[str, str], sep: float) -> float:
        e = self.emphasis(hexes)
        excess = max(0.0, (e - sm.EMPHASIS_BUDGET) / sm.EMPHASIS_BUDGET)
        return 1.0 - sep - sm.EMPHASIS_WEIGHT * excess

    def state_score(self, state: dict) -> dict:
        hexes = self.hexes(state)
        vals = self.term_values(hexes)
        sep = sm.shortfall(vals)["sep"]
        e = self.emphasis(hexes)
        excess = max(0.0, (e - sm.EMPHASIS_BUDGET) / sm.EMPHASIS_BUDGET)
        return {
            "utility": self.utility_from(hexes, sep),
            "sep": sep,
            "emph": e,
            "emph_excess": excess,
            "worst_margin": min(vals) if vals else 0.0,
            "mean_margin": (sum(vals) / len(vals)) if vals else 0.0,
            "at_target": sum(1 for v in vals if v >= 1.0),
            "terms": len(vals),
        }


