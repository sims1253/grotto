#: Same tolerance the gate and src/grotto/model.py use.
SAL_RANK_TOL = 2e-3

#: Chroma-fraction step used by the repair, and how many steps it may take
#: per pair before giving up on raising the higher-salience role.
SAL_REPAIR_STEP = 0.06
SAL_REPAIR_STEPS = 24

#: How many times the post-refinement repair sequence may run before the
#: search gives up and asserts.  Repairs interact; one pass is not enough.
POST_ROUNDS = 6


def _sf_unrepaired(sf: list[dict]) -> list[dict]:
    """same_family repairs that failed on a pair the optimizer owns."""
    return [e for e in sf if not e.get("repaired", True)]


@functools.lru_cache(maxsize=None)
def _normc(lch_hex: str) -> float:
    """Normalised chroma, C / max_chroma(L, h) -- the salience channel.

    Exactly the quantity src/grotto/model.py's realised-salience proxy
    compares, so the repair and the gate cannot disagree about what they
    measure.
    """
    from grotto.color import hex_to_oklch, max_chroma

    L, C, h = hex_to_oklch(lch_hex)
    mc = max_chroma(L, h, "srgb")
    return (C / mc) if mc > 1e-9 else 0.0


def _reversals_at(problem: SoftProblem, hexes: dict[str, str], role: str, new_hex: str) -> int:
    """Salience reversals ``role`` takes part in if it were ``new_hex``.

    Same pairs as ``salience_violations`` (adjacent, non-tied members of the
    role's hue family), on the in-search hexes; ``_normc`` is cached by hex so
    this is cheap enough for the ascent's inner loop.
    """
    n = 0
    for lo, hi in problem.sal_pairs.get(role, ()):
        a = new_hex if lo == role else hexes[lo]
        b = new_hex if hi == role else hexes[hi]
        if _normc_fast(a) - _normc_fast(b) > SAL_RANK_TOL:
            n += 1
    bg = hexes["bg"]
    for lo, hi in problem.prom_pairs.get(role, ()):
        a = new_hex if lo == role else hexes[lo]
        b = new_hex if hi == role else hexes[hi]
        if _prominence(a, bg) - _prominence(b, bg) > PROM_RANK_TOL:
            n += 1
    return n


def _in_srgb_fast(L: float, C: float, h: float) -> bool:
    """OKLCH -> linear sRGB in closed form (Ottosson's matrices)."""
    import math

    a = C * math.cos(math.radians(h))
    b = C * math.sin(math.radians(h))
    l_ = (L + 0.3963377774 * a + 0.2158037573 * b) ** 3
    m_ = (L - 0.1055613458 * a - 0.0638541728 * b) ** 3
    s_ = (L - 0.0894841775 * a - 1.2914855480 * b) ** 3
    eps = 1e-6
    for v in (
        4.0767416621 * l_ - 3.3077115913 * m_ + 0.2309699292 * s_,
        -1.2684380046 * l_ + 2.6097574011 * m_ - 0.3413193965 * s_,
        -0.0041960863 * l_ - 0.7034186147 * m_ + 1.7076147010 * s_,
    ):
        if v < -eps or v > 1.0 + eps:
            return False
    return True


@functools.lru_cache(maxsize=None)
def _normc_fast(lch_hex: str) -> float:
    """``_normc`` with a closed-form gamut test, for the ascent's guard only.

    ``grotto.color.max_chroma`` bisects through coloraide at ~1 ms a call,
    which put the guard over the benchmark's wall-clock cap.  The guard is a
    search heuristic; ``finalize`` and the gate still use the exact
    definition, so a disagreement can only cost a dropped candidate, never
    an inadmissible palette.
    """
    L, C, h = hex_to_oklch(lch_hex)
    if not _in_srgb_fast(L, 0.0, h):
        return 0.0
    lo, hi = 0.0, 0.5
    while hi - lo > 1e-5:
        mid = (lo + hi) / 2
        if _in_srgb_fast(L, mid, h):
            lo = mid
        else:
            hi = mid
    return (C / lo) if lo > 1e-9 else 0.0


#: Tolerance of the surface prominence rank, in OKLab dE from the canvas.
PROM_RANK_TOL = 1e-3


@functools.lru_cache(maxsize=None)
def _prominence(surf_hex: str, bg_hex: str) -> float:
    """How far a highlight surface stands off the canvas: OKLab dE."""
    return np_._dE(np_._oklab_of(surf_hex), np_._oklab_of(bg_hex))


def prominence_violations(problem: SoftProblem, hexes: dict[str, str]) -> list[tuple]:
    """Surface prominence reversals: (family, lower, higher, gap).

    For a background WASH the attention channel is not chroma alone but how
    far the wash stands off the canvas.  Normalised chroma flatters a wash
    parked next to the canvas, where the gamut is small: run 8's first
    probe shipped ``search_match_current`` (salience 5) at L 0.215, C 0.020
    -- the dimmest surface on screen -- beside a brighter ``search_match``
    (salience 4), and the normalised-chroma gate passed it.  So inside a hue
    family a higher-salience surface must stand at least as far off the
    canvas as a lower-salience one.
    """
    bg = hexes["bg"]
    out = []
    seen = set()
    for pairs in problem.prom_pairs.values():
        for lo, hi in pairs:
            if (lo, hi) in seen:
                continue
            seen.add((lo, hi))
            gap = _prominence(hexes[lo], bg) - _prominence(hexes[hi], bg)
            if gap > PROM_RANK_TOL:
                out.append((problem.roles_spec.roles[lo].family, lo, hi, gap))
    return sorted(out)


def salience_violations(problem: SoftProblem, hexes: dict[str, str]) -> list[tuple]:
    """Every within-family salience reversal in a palette, as tuples.

    Same definition as the gate and as ``src/grotto/model.py``: within a hue
    family, higher declared salience carries >= normalised chroma, tied
    salience imposes no ordering.
    """
    from grotto.color import max_chroma

    roles = problem.roles_spec.roles
    fams: dict[str, list[str]] = {}
    for r in problem.chromatic:
        fams.setdefault(roles[r].family, []).append(r)
    out: list[tuple] = []
    for fam, members in sorted(fams.items()):
        if len(members) < 2:
            continue
        sr = sorted(members, key=lambda r: roles[r].salience)
        for lo, hi in zip(sr, sr[1:]):
            if roles[lo].salience == roles[hi].salience:
                continue
            def normc(role: str) -> float:
                L, C, h = hex_to_oklch(hexes[role])
                mc = max_chroma(L, h, "srgb")
                return (C / mc) if mc > 1e-9 else 0.0

            gap = normc(lo) - normc(hi)
            if gap > SAL_RANK_TOL:
                out.append((fam, lo, hi, gap))
    return out


def _violations_touching(problem: SoftProblem, state: dict, role: str) -> int:
    """Salience reversals involving ``role`` in the palette the file will carry.

    Cheap enough to call inside the repair inner loops: only the (at most two)
    neighbouring pairs of ``role`` in its hue family are examined, so this is
    a handful of gamut-boundary bisections rather than a full sweep.
    """
    roles = problem.roles_spec.roles
    fam = roles[role].family
    members = sorted(
        (r for r in problem.chromatic if roles[r].family == fam),
        key=lambda r: roles[r].salience,
    )
    hexes = shipped_hexes(problem, state)
    n = 0
    for lo, hi in zip(members, members[1:]):
        if roles[lo].salience == roles[hi].salience:
            continue
        if role not in (lo, hi):
            continue
        if _normc(hexes[lo]) - _normc(hexes[hi]) > SAL_RANK_TOL:
            n += 1
    return n


def boost_normc(problem: SoftProblem, state: dict, role: str) -> bool:
    """Raise one role's normalised chroma as far as its fences allow.

    The salience channel is NORMALISED chroma, ``C / max_chroma(L, h)``, so
    it can be raised two ways: by raising ``C``, or by moving to a place where
    the sRGB gamut holds less chroma.  Raising ``C`` alone is not enough here:
    ``breakpoint`` (salience 5) is already at its chroma ceiling while the
    lower-salience ``diff_removed`` cannot go quieter, because the chroma floor
    holds it at 0.02.  Moving hue or lightness buys the same fraction without
    adding colour, which is also the more restrained answer.

    Every accepted move must not increase the number of salience reversals
    ``role`` takes part in.  Without that guard the repairs fight each other:
    boosting ``breakpoint`` past ``diff_removed`` fixes one pair and breaks
    ``breakpoint``/``error``, whose fallback then quietly undoes the boost.

    Returns True if the role moved.
    """
    current = _normc(shipped_hexes(problem, state)[role])
    violations = _violations_touching(problem, state, role)
    moved = False
    for _ in range(SAL_REPAIR_STEPS):
        hx = shipped_hexes(problem, state)
        best = None
        best_nc = current
        best_v = violations
        for axis, d in MOVES:
            got = _apply_move(problem, role, state[role], axis, d, hx)
            if got is None:
                continue
            probe = dict(state)
            probe[role] = got
            nc = _normc(shipped_hexes(problem, probe)[role])
            if nc <= best_nc + 1e-6:
                continue
            v = _violations_touching(problem, probe, role)
            if v > best_v:
                continue  # would fix this pair by breaking the neighbour's
            best_nc, best_v, best = nc, v, got
        if best is None:
            break
        state[role] = best
        current, violations = best_nc, best_v
        moved = True
    return moved


def enforce_salience_rank(problem: SoftProblem, state: dict) -> list[dict]:
    """Repair within-family salience reversals.  HARD output constraint.

    Same architecture as ``middle_palette.enforce_same_family_min``: the
    objective does not model it (nothing in the distance matrix ranks
    attention), so it cannot be traded off inside the ascent -- it is repaired
    afterwards, inside the same fences, through the same move machinery, and
    then re-checked.

    Two passes per violating pair: raise the higher-salience role's normalised
    chroma (``boost_normc``) and lower the lower-salience role's chroma, in
    whichever order leaves the better final utility.  Both passes accept a move only if it does
    not increase the reversals the moved role takes part in, which is what
    makes the sequence converge instead of oscillating.

    Progress is measured in normalised chroma, never in coordinates: the
    chroma ceiling clamps a coordinate move to no change while the surrounding
    hexes still shift, so a coordinate test reports "no progress" on moves
    that are in fact repairing the pair.

    Reports what it could not fix rather than hiding it.
    """
    report: list[dict] = []
    for fam, lo, hi, _gap in salience_violations(problem, shipped_hexes(problem, state)):
        # Either order can be the cheap one.  Raising the higher-salience role
        # first was the only order until run 10, and it paid ~0.02 utility on
        # every seed: ``error`` has 9 objective terms, ``breakpoint`` (placed
        # after the ascent, no terms at all) is free to quiet.  So both orders
        # run on copies and the better FINAL utility wins.
        tried = []
        for order in ((_raise_normc, _lower_normc), (_lower_normc, _raise_normc)):
            trial = dict(state)
            for step in order:
                step(problem, trial, lo, hi)
            hx = shipped_hexes(problem, trial)
            gap = _normc(hx[lo]) - _normc(hx[hi])
            tried.append((gap <= SAL_RANK_TOL, _shipped_utility(problem, trial), -gap, trial))
        fixed, _u, neg_gap, best = max(tried, key=lambda t: (t[0], t[1], t[2]))
        state.clear()
        state.update(best)
        if not fixed:
            report.append({
                "family": fam,
                "lower_salience": lo,
                "higher_salience": hi,
                "repaired": False,
                "normc_gap": round(-neg_gap, 5),
            })
    return report


def _shipped_utility(problem: SoftProblem, state: dict) -> float:
    hexes = shipped_hexes(problem, state)
    return problem.utility_from(hexes, sm.shortfall(problem.term_values(hexes))["sep"])


def _raise_normc(problem: SoftProblem, state: dict, lo: str, hi: str) -> None:
    """Raise the higher-salience role until the pair is in order (or stuck)."""
    for _ in range(POST_ROUNDS):
        hexes = shipped_hexes(problem, state)
        if _normc(hexes[lo]) - _normc(hexes[hi]) <= SAL_RANK_TOL:
            return
        if not boost_normc(problem, state, hi):
            return


def _lower_normc(problem: SoftProblem, state: dict, lo: str, hi: str) -> None:
    """Quiet the lower-salience role's chroma until the pair is in order.

    A step that makes no progress, or that would reverse one of the role's
    other pairs, is undone rather than left in place.
    """
    hexes = shipped_hexes(problem, state)
    for _ in range(SAL_REPAIR_STEPS):
        if _normc(hexes[lo]) - _normc(hexes[hi]) <= SAL_RANK_TOL:
            return
        before = _violations_touching(problem, state, lo)
        prev_nc = _normc(hexes[lo])
        prev = state[lo]
        got = _apply_move(problem, lo, state[lo], "f", -SAL_REPAIR_STEP, hexes)
        if got is None:
            return
        state[lo] = got
        hexes = shipped_hexes(problem, state)
        if (_violations_touching(problem, state, lo) > before
                or _normc(hexes[lo]) >= prev_nc - 1e-9):
            state[lo] = prev
            return


def repair_prominence(problem: SoftProblem, state: dict, steps: int = 30) -> None:
    """Restore the surface prominence rank by moving SURFACES only.

    For a reversed pair, first push the higher-salience surface further off
    the canvas, then pull the lower-salience one toward it -- each move on
    the lightness or chroma axis, through the fenced move machinery (so WCAG,
    gamut and every fence still hold), and accepted only if it shrinks the
    gap without adding a salience or prominence reversal elsewhere.
    """
    for _ in range(steps):
        hexes = shipped_hexes(problem, state)
        bad = prominence_violations(problem, hexes)
        if not bad:
            return
        _fam, lo, hi, gap = bad[0]
        moved = False
        for role, moves in ((hi, (("L", 0.01), ("f", 0.12))),
                            (lo, (("L", -0.01), ("f", -0.12)))):
            before = _reversals_at(problem, hexes, role, hexes[role])
            for axis, d in moves:
                got = _apply_move(problem, role, state[role], axis, d, hexes)
                if got is None:
                    continue
                probe = dict(state)
                probe[role] = got
                hx = shipped_hexes(problem, probe)
                g2 = (_prominence(hx[lo], hx["bg"]) - _prominence(hx[hi], hx["bg"]))
                if g2 < gap - 1e-6 and _reversals_at(problem, hx, role, hx[role]) <= before:
                    state[role] = got
                    moved = True
                    break
            if moved:
                break
        if not moved:
            return


def finalize(problem: SoftProblem, state: dict, out: Path) -> dict | None:
    """Run every hard output constraint over a refined palette, to a fixed point.

    Returns ``{state, hexes, score}`` for a palette that satisfies every gate,
    or ``None`` when a constraint could not be met -- the caller reports that
    rather than emitting a palette that fails its own gate afterwards.

    The constraints here are REPAIRS, not filters: they move colours, so the
    result can score worse than its input.  That is why selection happens on
    this function's output and not on the ascent's.
    """
    state = mp.place_unconstrained_fenced(problem, dict(state))
    # The placement grid knows the middle fences, not the chroma floor.
    for r in problem.chromatic:
        if not problem.term_ids_by_role.get(r):
            state[r] = problem.fence_lch(r, *state[r])
    # Repairs interact: nudging a surface to restore a WCAG floor changes its
    # lightness, which changes max_chroma(L, h), which changes its normalised
    # chroma and re-opens a salience pair the previous repair had just fixed.
    # Running the sequence repeatedly is what makes the emitted palette
    # satisfy every hard output constraint at once.
    sf = sal = bad = []
    for _ in range(POST_ROUNDS):
        sf = mp.enforce_same_family_min(problem, state)
        sal = enforce_salience_rank(problem, state)
        bad = repair_wcag(problem, state)
        if not bad and not sal and not _sf_unrepaired(sf):
            break
    if bad:
        return {"error": f"WCAG unrepairable: {bad}"}
    if _sf_unrepaired(sf):
        return {"error": f"same_family unrepairable: {_sf_unrepaired(sf)}"}
    unrepaired = [e for e in sal if not e["repaired"]]
    if unrepaired:
        return {"error": f"salience rank unrepairable: {unrepaired}"}
    left = salience_violations(problem, shipped_hexes(problem, state))
    if left:
        return {"error": f"repairs did not converge: {left}"}
    repair_prominence(problem, state)
    prom = prominence_violations(problem, shipped_hexes(problem, state))
    if prom:
        return {"error": f"surface prominence reversed: {prom}"}
    hexes = shipped_hexes(problem, state)
    fences = problem.fence_audit(hexes) + problem.fence_audit_state(state)
    if fences:
        return {"error": f"left the fences: {fences}"}
    # The written file must reproduce exactly the colours everything else
    # agreed on.  If it does not, refuse to emit rather than ship a palette
    # that fails its own gate after the fact.
    probe = out / ".verify.night.yaml"
    mp.write_palette_yaml(probe, "verify", state, problem, 0, {})
    reread = {r: str(v) for r, v in Palette.from_yaml(probe).colors.items()}
    drift = [r for r in problem.chromatic if reread[r] != hexes[r]]
    probe.unlink()
    if drift:
        return {"error": f"written palette drifts from the shipped hexes: {drift}"}
    return {"state": state, "hexes": hexes, "score": problem.state_score(state)}


