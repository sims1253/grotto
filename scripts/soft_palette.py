def main() -> None:
    ap = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    ap.add_argument("--seed", type=int, default=DEFAULT_SEED)
    ap.add_argument("--restarts", type=int, default=8)
    ap.add_argument("--samples", type=int, default=8)
    ap.add_argument("--refine-passes", type=int, default=12)
    ap.add_argument("--n-palettes", type=int, default=1)
    ap.add_argument("--select", type=int, default=3,
                    help="candidates to post-process before picking the best final one")
    ap.add_argument("--out", default=None,
                    help=f"default {DEFAULT_OUT}; {CVD_OUT} for --profile cvd, {DAY_OUT} for day")
    ap.add_argument("--profile", choices=sorted(PROFILES), default="default")
    ap.add_argument("--no-install", action="store_true")
    args = ap.parse_args()

    t0 = time.monotonic()
    c0 = time.process_time()
    out = REPO / (args.out or {"cvd": CVD_OUT, "day": DAY_OUT}.get(args.profile, DEFAULT_OUT))
    out.mkdir(parents=True, exist_ok=True)
    problem = SoftProblem(profile=args.profile)
    prefix = {"cvd": CVD_PREFIX, "day": DAY_PREFIX}.get(args.profile, PALETTE_PREFIX)
    prov = {"cvd": CVD_PROVENANCE, "day": DAY_PROVENANCE}.get(args.profile, SOFT_PROVENANCE)
    variant = prov.get("variant", "night")
    print(
        f"[problem] {len(problem.chromatic)} chromatic roles inside the middle "
        f"fences; {len(problem.terms)} objective terms; "
        f"{len(problem.same_family_pairs)} same_family pairs; "
        f"emphasis over {len(problem._emph_roles)} weighted roles, "
        f"budget {sm.EMPHASIS_BUDGET:.3f} weight {sm.EMPHASIS_WEIGHT:.2f}"
    )

    results = run_search(
        problem, seed=args.seed, restarts=args.restarts, samples=args.samples,
        refine_passes=args.refine_passes, log=print,
    )
    print(
        f"[search] {len(results)} refined results in {time.monotonic() - t0:.1f}s; "
        f"best utility={results[0]['utility']:.4f}"
    )

    # ---- selection on the FINAL palette, not the pre-repair one ----------
    # The hard output constraints are REPAIRS, not filters: they move colours
    # after the ascent has finished.  A repair can REORDER candidates.
    # Measured at the full budget: the best pre-repair candidate (utility
    # 0.9479) finished post-repair at 0.9360, while a slightly worse starting
    # point finished at 0.9365.  Ranking on the pre-repair score therefore
    # picks the wrong palette -- so post-process the strongest few candidates
    # and keep the best result of the WHOLE pipeline.
    shortlist = np_.diverse_pick(results, args.select, min_mean_dh=15.0)
    print(f"[select] post-processing {len(shortlist)} candidate(s); keeping the best "
          f"FINAL utility, not the best pre-repair one")
    finished = []
    for r in shortlist:
        done = finalize(problem, dict(r["state"]), out)
        if "error" in done:
            # Reported, never silent: a dropped candidate is information about
            # where the repairs cannot reach, not a rounding error to hide.
            print(f"[select]   {r['kind']}: dropped -- {done['error']}")
            continue
        finished.append({"state": done["state"], "hexes": done["hexes"],
                         "score": done["score"], "kind": r["kind"],
                         "pre": r["utility"]})
        print(f"[select]   {r['kind']}: pre-repair {r['utility']:.4f} "
              f"-> final {done['score']['utility']:.4f}")
    if not finished:
        raise SystemExit("no candidate survived post-processing")
    finished.sort(key=lambda d: -d["score"]["utility"])

    entries = []
    for i, d in enumerate(finished[: args.n_palettes], 1):
        state, hexes, sc = d["state"], d["hexes"], d["score"]
        name = f"{prefix}{i:02d}"
        path = out / f"{name}.{variant}.yaml"
        mp.write_palette_yaml(
            path, name, state, problem, args.seed,
            {"profile": args.profile,
             "restart-kind": d["kind"], "utility": round(sc["utility"], 5),
             "sep": round(sc["sep"], 5), "emphasis": round(sc["emph"], 5),
             "worst-margin": round(sc["worst_margin"], 5),
             "at-target": sc["at_target"],
             "pre-repair-utility": round(d["pre"], 5)},
            provenance=prov,
        )
        # Two metric blocks on purpose: `score` is this session's soft
        # objective, `metrics` is the middle-frontier report block the shared
        # renderer expects, so the preview page is directly comparable with
        # out/middle-night and out/numeric-night.
        entries.append({"label": name, "state": state, "hexes": hexes,
                        "score": sc,
                        "metrics": mp.middle_palette_metrics(problem, hexes),
                        "source_name": path.name,
                        "kind": f"soft ({d['kind']} restart)"})
        print(
            f"[palette] {name}: utility={sc['utility']:.4f} sep={sc['sep']:.4f} "
            f"emph={sc['emph']:.4f} worst={sc['worst_margin']:.4f} "
            f"atTarget={sc['at_target']}/{sc['terms']}"
        )

    base_path = REPO / "themes/candidates" / problem.scaffold_source
    base = sm.score(base_path)
    # Comparison entries for the preview page: the committed candidate-b Night
    # palette first, then the picks, then the rejected numeric frontier last --
    # the same ordering middle_palette.py uses, so the three pages read alike.
    base_hexes = shipped_hexes(problem, problem.baseline_lch)
    entries.insert(
        0,
        {"label": "candidate-b-balanced", "kind": "committed candidate (baseline)",
         "hexes": base_hexes, "score": sm.score(base_path),
         "metrics": mp.middle_palette_metrics(problem, base_hexes),
         "source_name": problem.scaffold_source, "state": problem.baseline_lch},
    )
    night_refs = (
        (REPO / "out/soft-night/soft-s01.night.yaml", "soft-s01 (v1)"),
        (REPO / "out/middle-night/middle-m01.night.yaml", "middle-m01"),
        (REPO / "out/numeric-night/numeric-n01.night.yaml", "numeric-n01"),
    )
    for ref_path, ref_label in (night_refs if variant == "night" else ()):
        if ref_path.exists():
            ref_colors = {r: str(v) for r, v in Palette.from_yaml(ref_path).colors.items()}
            ref_hexes = {r: ref_colors[r] for r in problem.present if r in ref_colors}
            entries.append(
                {"label": ref_label, "kind": "frontier reference",
                 "hexes": ref_hexes, "score": sm.score(ref_path),
                 "metrics": mp.middle_palette_metrics(problem, ref_hexes),
                 "source_name": ref_path.name, "state": None}
            )

    # Installable preview: the deliverable.  A palette nobody can look at is
    # not finished, and every conclusion in this session rests on appearance
    # judgements the owner has to make in a real editor.
    mp.write_variants_html(
        out / "variants.html", problem, entries,
        provenance=prov["html"],
    )
    mp.write_vscode_extension(
        out / "vscode-preview", problem,
        [{"label": e["label"], "hexes": e["hexes"], "source_name": e["source_name"],
          "sha": "soft-exploration"} for e in entries if e["label"].startswith(prefix)],
        k=3, install=not args.no_install,
        provenance=prov["extension"],
    )

    metrics = {
        "schema": "grotto.soft-night",
        "schema_version": "1",
        "generated_by": "scripts/soft_palette.py",
        "seed": args.seed,
        "restarts": args.restarts,
        "samples": args.samples,
        "refine_passes": args.refine_passes,
        "objective": {
            "formula": "utility = 1 - SEP - EMPHASIS_WEIGHT * EMPHASIS_EXCESS",
            "shortfall": "SEP = mean over all terms of max(0, 1 - margin)**SHORTFALL_EXP",
            "shortfall_exp": sm.SHORTFALL_EXP,
            "emphasis": "area-weighted mean chroma; measured character share for inks, "
                        "declared area_class share for surfaces (canvas excluded)",
            "emphasis_budget": sm.EMPHASIS_BUDGET,
            "emphasis_weight": sm.EMPHASIS_WEIGHT,
            "area_class_share": sm.AREA_CLASS_SHARE,
            "surface_area_weight": sm.SURFACE_AREA_WEIGHT,
            "acceptance": "strict on utility; no mean-margin tie-break",
        },
        "fences": {
            "inherited": "scripts/middle_palette.py (hue windows, L deltas, chroma caps, 70% gamut)",
            "scaffold_l_overrides": SCAFFOLD_L_OVERRIDES,
            "lightness_offset_l_delta": {"ink_down": OFFSET_INK_L_DELTA,
                                         "surface": OFFSET_SURFACE_L_DELTA},
            "soft_hue_windows": {r: [list(w) for w in ws] for r, ws in SOFT_HUE_WINDOWS.items()},
            "role_chroma_floor": ROLE_CHROMA_FLOOR,
            "role_l_max": ROLE_L_MAX,
            "chroma_floor": sm.CHROMA_FLOOR,
            "gates": ["salience-rank (normalised chroma)", "surface prominence (dE off canvas)"],
        },
        "palettes": entries,
        "reference": base,
        "wall_seconds": round(time.monotonic() - t0, 2),
    }
    # sort_keys keeps this artifact byte-stable across runs: the palette is
    # seeded and deterministic, so any other ordering churn would be pure
    # noise in review.  `wall_seconds` is the one field that must vary -- it is
    # a run statistic, not a claim about the palette.
    (out / "metrics.json").write_text(
        json.dumps(metrics, indent=2, sort_keys=True) + "\n", encoding="utf-8"
    )
    print(
        f"[reference] {problem.scaffold_source}: utility={base['utility']:.4f} "
        f"sep={base['sep']:.4f} emph={base['emph']:.4f} "
        f"worst={base['worst_margin']:.4f} wcag_violations={base['wcag_violations']}"
    )
    for e in entries[2:]:
        r = e["score"]
        print(
            f"[reference] {e['label']}: utility={r['utility']:.4f} "
            f"sep={r['sep']:.4f} emph={r['emph']:.4f} "
            f"worst={r['worst_margin']:.4f}"
        )
    print(f"[done] {time.monotonic() - t0:.1f}s total, "
          f"{time.process_time() - c0:.1f}s cpu; artifacts in {out}")


if __name__ == "__main__":
    main()